function t(lang, path) {
  const parts = String(path).split('.');
  let node = translations[lang] || translations.fa;
  for (const p of parts) {
    if (node && Object.prototype.hasOwnProperty.call(node, p)) {
      node = node[p];
    } else {
      return '';
    }
  }
  return node;
}

